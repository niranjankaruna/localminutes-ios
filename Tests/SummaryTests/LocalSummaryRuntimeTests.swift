import Foundation
import XCTest
@testable import LocalMinutesSummary

private struct ActualSummaryFixture: Decodable {
    let decision: String
    let action_owner: String
    let action_task: String
    let action_due: String
    let budget_decided: Bool
    let evidence: [String]
}

@MainActor
final class LocalSummaryRuntimeTests: XCTestCase {
    private let prompt = """
    Extract only the following original fictional meeting evidence.
    [s1] Maya: We decided to ship the prototype on Friday.
    [s2] Leo: I will write the installation guide by Thursday.
    [s3] Maya: The training budget remains undecided.
    Return only one valid JSON object, with no Markdown, matching these keys:
    decision (string), action_owner (exact speaker name), action_task (string),
    action_due (string), budget_decided (boolean), evidence (array of segment IDs).
    The speaker who says "I will" owns that action. Preserve uncertainty.
    """

    // Explicit caller schema follows the measured action-first contract. Names,
    // dates, tasks and decisions are still generated by the actual model.
    private let schema = StructuredJSONSchema(fields: [
        .init(name: "action_task", type: .string), .init(name: "action_owner", type: .string),
        .init(name: "action_due", type: .string), .init(name: "decision", type: .string),
        .init(name: "budget_decided", type: .boolean),
        .init(name: "evidence", type: .stringArray(allowedValues: ["s1", "s2", "s3"]))
    ])

    private func actualModelURL() throws -> URL {
        let path = try XCTUnwrap(ProcessInfo.processInfo.environment["LOCALMINUTES_QWEN_MODEL_PATH"],
            "Dedicated actual-model suite requires the pinned real model; absence is a failure, never a skip")
        let url = URL(fileURLWithPath: path)
        let attributes = try FileManager.default.attributesOfItem(atPath: url.path)
        XCTAssertEqual((attributes[.size] as? NSNumber)?.int64Value, 1_117_320_736)
        return url
    }

    func testActualQwenProducesValidJSONWithCorrectActionSpeakerAndDecision() async throws {
        let runtime = try LocalSummaryRuntime(modelURL: actualModelURL())
        let output = try await runtime.generateJSON(prompt: prompt, schema: schema)
        let result = try JSONDecoder().decode(ActualSummaryFixture.self, from: Data(output.utf8))
        XCTAssertEqual(result.action_owner, "Leo", "Real candidate previously misattributed this action to Maya")
        XCTAssertTrue(result.action_task.lowercased().contains("installation guide"))
        XCTAssertEqual(result.action_due, "Thursday")
        XCTAssertTrue(result.decision.lowercased().contains("prototype"))
        XCTAssertTrue(result.decision.contains("Friday"))
    }

    func testActualQwenPreservesUnknownBudgetAndReturnsOnlySuppliedEvidenceIDs() async throws {
        let runtime = try LocalSummaryRuntime(modelURL: actualModelURL())
        let output = try await runtime.generateJSON(prompt: prompt, schema: schema)
        let result = try JSONDecoder().decode(ActualSummaryFixture.self, from: Data(output.utf8))
        XCTAssertFalse(result.budget_decided)
        XCTAssertFalse(result.evidence.isEmpty)
        XCTAssertTrue(Set(result.evidence).isSubset(of: ["s1", "s2", "s3"]))
        XCTAssertTrue(result.evidence.contains("s2"), "An action must cite its actual supporting segment")
    }

    func testNativeSummaryLoadRejectsMissingAndInvalidGGUF() throws {
        let parent = FileManager.default.temporaryDirectory.standardizedFileURL
        let root = parent.appendingPathComponent("localminutes-llm-test-\(UUID().uuidString)", isDirectory: true)
        try FileManager.default.createDirectory(at: root, withIntermediateDirectories: false)
        defer { try? FileManager.default.removeItem(at: root) }
        XCTAssertThrowsError(try LocalSummaryRuntime(modelURL: root.appendingPathComponent("missing.gguf"))) {
            XCTAssertEqual($0 as? LocalSummaryRuntimeError, .modelUnavailable)
        }
        let invalid = root.appendingPathComponent("invalid.gguf")
        try Data("original non-model integrity fixture".utf8).write(to: invalid)
        XCTAssertThrowsError(try LocalSummaryRuntime(modelURL: invalid)) {
            XCTAssertEqual($0 as? LocalSummaryRuntimeError, .invalidModel)
        }
    }

    func testCancelledNativeGenerationDoesNotPublishAndRuntimeCanBeReused() async throws {
        let runtime = try LocalSummaryRuntime(modelURL: actualModelURL())
        let input = prompt
        let inputSchema = schema
        let task = Task { try await runtime.generateJSON(prompt: input, schema: inputSchema, maximumTokens: 192) }
        task.cancel()
        do { _ = try await task.value; XCTFail("Cancelled generation published a summary") }
        catch is CancellationError { }
        catch { XCTFail("Expected explicit cancellation, got \(error)") }
        let next = try await runtime.generateJSON(prompt: prompt, schema: schema)
        let result = try JSONDecoder().decode(ActualSummaryFixture.self, from: Data(next.utf8))
        XCTAssertEqual(result.action_owner, "Leo")
        XCTAssertFalse(result.budget_decided)
    }
}
